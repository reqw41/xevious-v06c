; Опоздавшее обновление (вывод начался не сразу после прерывания): прокрутка сменится только со следующего
; прерывания, а нарисованная заранее строка была бы видна внизу полосы. Поэтому основной код строку только
; готовит — номера тайлов и коды наложения в свои буферы (TL_PRIV, OV_PRIV; кеш карты и буферы строк основного
; кода прерыванию трогать нельзя), — а рисует её следующее прерывание сразу после новой прокрутки (lb_out), там же
; рисуется панель. Ушедшую в полосу строку чистит band_clear после стирания спрайтов: иначе их старый фон
; может вернуться в уже очищенную строку. До того верх поля для спрайтов и тайлов — на строку ниже
; (clip_base = 17). Отложенные тайлы этой строки дорисует основной код в начале следующего обновления (pl_dy).
; clip_base снимается только здесь: lb_out уже вывел строку, но pend_line ещё может её затереть.
; pend_def: отложенные тайлы прошлой опоздавшей строки (прерывание список не трогает)
pend_def:
	ld	a,(pl_dy)
	or	a
	ret	z
	xor	a
	ld	(pl_dy),a
	ld	a,(pl_dyv)
	ld	(pl_y),a
	call	pend_line
	ld	a,16
	ld	(clip_base),a
	jp	mark_pending
; Вход: HL — номера тайлов (draw_top_line при top_now = 0), (ol_row), (ol_off), (top_codes), (pl_y).
lb_save:
	ld	de,TL_PRIV
	call	cp15
	ld	hl,TL_PRIV
	call	TOPL_SET
	ld	a,(pl_y)
	push	af
	call	pend_def	; отложенные тайлы прошлой опоздавшей строки
	pop	af
	ld	(pl_y),a
	ld	hl,(top_codes)
	ld	de,OV_PRIV
	call	cp15
	ld	a,(hl)		; признак «есть наложение»
	ld	(de),a
	ld	a,(pl_y)		; отложенные тайлы этой строки — в начале следующего обновления
	ld	(pl_dyv),a
	ld	a,1
	ld	(pl_dy),a
	ld	a,(CAM_Y)
	add	a,240
	cpl
	ld	(lb_q),a
	ld	a,(vs_cur)
	ld	(lb_vs),a
	ld	a,17
	ld	(clip_base),a
	xor	a
	ld	(hud_req),a
	inc	a
	ld	(band_n),a	; очистка после стирания спрайтов, в том числе при поздней прокрутке
	ld	(lb_pend),a
	ret
